-- =====================================================================
-- 02  Star schema: FactSales + 5 dimensions (dimensions are NOT linked
--     to each other; geography of customers/sellers is denormalised).
--     Every dimension has an Unknown member with key -1 (date: 0).
-- =====================================================================
CREATE TABLE IF NOT EXISTS dw.dim_date (
    date_key        INT PRIMARY KEY,          -- yyyymmdd, 0 = Unknown
    full_date       DATE,
    day_of_month    SMALLINT,
    day_name        TEXT,
    day_of_week     SMALLINT,                 -- 1 = Monday
    week_of_year    SMALLINT,
    week_start      DATE,
    month_num       SMALLINT,
    month_name      TEXT,
    month_start     DATE,
    year_month      TEXT,                     -- 2024-03
    quarter         TEXT,                     -- Q1
    year            SMALLINT,
    is_weekend      BOOLEAN,
    is_ramadan      BOOLEAN,
    is_eid_ul_fitr  BOOLEAN,
    is_eid_ul_adha  BOOLEAN,
    is_independence_day BOOLEAN,
    is_11_11        BOOLEAN,
    is_black_friday BOOLEAN,
    is_event_day    BOOLEAN,
    event_name      TEXT                      -- Ramadan / Eid-ul-Fitr / ... / 'Regular day'
);

CREATE TABLE IF NOT EXISTS dw.dim_location (
    location_key    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id         INT UNIQUE,
    city            TEXT,
    province        TEXT,
    region          TEXT,
    population_tier TEXT,
    latitude        NUMERIC(9,4),
    longitude       NUMERIC(9,4)
);

CREATE TABLE IF NOT EXISTS dw.dim_customer (            -- SCD Type 1 (overwrite on change)
    customer_key      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id       TEXT UNIQUE,                       -- master ID after de-duplication
    full_name         TEXT,
    email             TEXT,
    phone             TEXT,
    gender            TEXT,
    birth_year        INT,
    age_band          TEXT,
    registration_date DATE,
    city              TEXT,
    province          TEXT,
    region            TEXT,
    population_tier   TEXT,
    first_order_date  DATE,
    rfm_recency_days  INT,
    rfm_frequency     INT,
    rfm_monetary      NUMERIC(16,2),
    rfm_r             SMALLINT,
    rfm_f             SMALLINT,
    rfm_m             SMALLINT,
    rfm_segment       TEXT,
    n_source_ids      INT,
    updated_at        TIMESTAMP DEFAULT now()
);

CREATE TABLE IF NOT EXISTS dw.dim_product (
    product_key   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    TEXT UNIQUE,
    product_name  TEXT,
    category      TEXT,
    sub_category  TEXT,
    brand         TEXT,
    list_price    NUMERIC(14,2),
    cost_price    NUMERIC(14,2),
    weight_kg     NUMERIC(8,3),
    price_band    TEXT
);

CREATE TABLE IF NOT EXISTS dw.dim_seller (
    seller_key      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id       TEXT UNIQUE,
    seller_name     TEXT,
    join_date       DATE,
    seller_tier     TEXT,
    rating          NUMERIC(3,1),
    city            TEXT,
    province        TEXT,
    region          TEXT,
    population_tier TEXT
);

CREATE TABLE IF NOT EXISTS dw.fact_sales (               -- grain: one row per order line
    sales_key        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_key         INT NOT NULL REFERENCES dw.dim_date(date_key),
    customer_key     INT NOT NULL REFERENCES dw.dim_customer(customer_key),
    product_key      INT NOT NULL REFERENCES dw.dim_product(product_key),
    seller_key       INT NOT NULL REFERENCES dw.dim_seller(seller_key),
    location_key     INT NOT NULL REFERENCES dw.dim_location(location_key),
    return_date_key  INT NOT NULL REFERENCES dw.dim_date(date_key),
    order_id         TEXT NOT NULL,
    order_item_id    TEXT NOT NULL UNIQUE,
    quantity         INT,
    unit_price       NUMERIC(14,2),
    gross_amount     NUMERIC(16,2),       -- quantity * unit_price
    discount_pct     NUMERIC(5,2),
    discount_amount  NUMERIC(16,2),
    net_amount       NUMERIC(16,2),       -- gross - discount
    unit_cost        NUMERIC(14,2),
    cost_amount      NUMERIC(16,2),       -- cost_price * quantity
    shipping_fee     NUMERIC(18,6),       -- order fee allocated by line gross share
    shipping_days    INT,                 -- shipped -> delivered
    delivery_days    INT,                 -- order date -> delivered
    is_on_time       SMALLINT,            -- delivery_days <= 5 (see README)
    courier          TEXT,
    is_cancelled     SMALLINT,
    is_in_transit    SMALLINT,
    is_delivered_line SMALLINT,           -- non-cancelled and not In Transit
    is_returned      SMALLINT,            -- has a valid (non-Rejected) return
    returned_amount  NUMERIC(16,2),       -- valid refund for the line
    return_reason    TEXT,
    return_status    TEXT,
    order_status     TEXT,
    payment_method   TEXT,
    channel          TEXT,
    discount_code    TEXT,
    is_first_order   SMALLINT,            -- customer's first non-cancelled order
    is_repaired      SMALLINT,            -- any field repaired during cleaning
    loaded_at        TIMESTAMP DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_fact_date     ON dw.fact_sales(date_key);
CREATE INDEX IF NOT EXISTS ix_fact_customer ON dw.fact_sales(customer_key);
CREATE INDEX IF NOT EXISTS ix_fact_product  ON dw.fact_sales(product_key);
CREATE INDEX IF NOT EXISTS ix_fact_seller   ON dw.fact_sales(seller_key);
CREATE INDEX IF NOT EXISTS ix_fact_location ON dw.fact_sales(location_key);
CREATE INDEX IF NOT EXISTS ix_fact_order    ON dw.fact_sales(order_id);
